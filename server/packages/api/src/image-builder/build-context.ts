import { ENVIRONMENT_VARIABLE_NAME } from "@oma-server/sandbox";
import type { EnvironmentVariable } from "@oma-server/store";
import type { BuildContextFiles } from "./ports.js";

/**
 * The context of one Environment Build (ADR-0024 "Building"): the generated
 * Dockerfile, the init script, `build.env` and the build pod's driver. Users
 * never write a Dockerfile.
 *
 * Variables reach the script only through the bind-mounted `build.env`,
 * never `ARG` or `ENV`, which would land in the image history or config:
 * platform defaults, then the build-time proxy, then the Environment's plain
 * variables. Secrets never enter a build, neither the Environment's nor the
 * platform's.
 */
export interface BuildContextInput {
  environmentId: string;
  buildId: string;
  /** The Base Image, pinned by digest. */
  baseImage: string;
  initScript: string;
  /** The Environment's variables; only the plain ones are used. */
  env: readonly EnvironmentVariable[];
  /** Deployment defaults, lowest priority (`PLATFORM_DEFAULT_ENV`). */
  platformDefaults: Readonly<Record<string, string>>;
  /** The cluster's egress proxy for downloads the mirrors do not serve (GitHub). */
  proxy: { url: string; noProxy: string } | null;
  /** The attempt's marker token; see {@link BuildJob.nonce}. */
  nonce: string;
}

/** Where the build pod mounts the context (a ConfigMap). */
export const BUILD_CONTEXT_DIR = "/oma/context";

/** A value as one single-quoted word for `sh`: nothing in it is expanded. */
export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

/**
 * `build.env`, sourced with `set -a` before the script: later lines win, so
 * an Environment variable overrides a default or the build proxy.
 */
export function buildEnvFile(input: Pick<BuildContextInput, "env" | "platformDefaults" | "proxy">): string {
  const values = new Map<string, string>(Object.entries(input.platformDefaults));
  if (input.proxy) {
    for (const name of ["HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"]) values.set(name, input.proxy.url);
    for (const name of ["NO_PROXY", "no_proxy"]) values.set(name, input.proxy.noProxy);
  }
  for (const variable of input.env) {
    // A secret reference carries no value and never reaches a build.
    if ("secretRef" in variable) continue;
    values.delete(variable.name);
    values.set(variable.name, variable.value);
  }
  const lines = ["# Variables of this build (oma-image-builder). Never secrets; not kept in the image."];
  for (const [name, value] of values) {
    if (!ENVIRONMENT_VARIABLE_NAME.test(name)) throw new Error(`Invalid build variable name: ${name}`);
    lines.push(`${name}=${shellQuote(value)}`);
  }
  return `${lines.join("\n")}\n`;
}

const DOCKERFILE_LABEL = /^[A-Za-z0-9_-]+$/;

/**
 * The generated Dockerfile, in ADR-0024's shape. The init step adds the
 * script's failure location (the ERR trap in `init-trap.sh`) and a marker
 * the driver tells a script failure by; the manifest step marks its own
 * failure, which only what the script left can cause.
 */
export function dockerfile(input: Pick<BuildContextInput, "environmentId" | "buildId" | "baseImage" | "nonce">): string {
  for (const id of [input.environmentId, input.buildId, input.nonce]) {
    if (!DOCKERFILE_LABEL.test(id)) throw new Error(`Invalid build identity: ${id}`);
  }
  return [
    `# Generated by oma-image-builder (ADR-0024): Environment ${input.environmentId}, build ${input.buildId}.`,
    `FROM ${input.baseImage}`,
    "RUN --mount=type=bind,source=init.sh,target=/tmp/oma-init.sh \\",
    "    --mount=type=bind,source=build.env,target=/tmp/oma-build.env \\",
    "    --mount=type=bind,source=init-trap.sh,target=/tmp/oma-init-trap.sh \\",
    "    cd /home/user && set -a && . /tmp/oma-build.env && set +a && \\",
    "    { BASH_ENV=/tmp/oma-init-trap.sh bash -euo pipefail /tmp/oma-init.sh \\",
    `      || { status=$?; echo "OMA_INIT_FAILED ${input.nonce} exit=$status" >&2; exit "$status"; }; }`,
    `RUN { /opt/oma/bin/write-manifest > /opt/oma/manifest.json || { echo "OMA_MANIFEST_FAILED ${input.nonce}" >&2; exit 1; }; } \\`,
    "    && find /home/user \\( ! -user user -o ! -group user \\) -exec chown -h user:user {} + \\",
    "    && rm -rf /var/lib/apt/lists/* /root/.cache /tmp/*",
    `LABEL dev.oma.environment="${input.environmentId}" dev.oma.build="${input.buildId}"`,
    "",
  ].join("\n");
}

/** Sourced by the script's bash (`BASH_ENV`) before the script: names the failing line. */
export const INIT_TRAP = `# Sourced before the init script (oma-image-builder): report where it failed.
unset BASH_ENV
set -E
trap 'oma_status=$?; printf "\\n[oma] init script failed at line %s: %s (exit status %s)\\n" "$LINENO" "$BASH_COMMAND" "$oma_status" >&2' ERR
`;

/**
 * containers-storage for an unprivileged ACS pod (#299): native overlay
 * without mount_program on the emptyDir; vfs fills the disk and
 * fuse-overlayfs needs /dev/fuse.
 */
export const STORAGE_CONF = `[storage]
driver = "overlay"
runroot = "/run/containers/storage"
graphroot = "/var/lib/containers/storage"
[storage.options.overlay]
mountopt = "nodev"
`;

/**
 * The build pod's driver. It pulls the Base Image first and on its own, so a
 * failed pull is told from the build; builds the generated Dockerfile with
 * chroot isolation; pushes one OCI manifest; and reports the outcome as JSON
 * in the termination message and, behind the attempt's nonce, in the log.
 * Nothing it prints holds a credential.
 */
export const BUILD_DRIVER = `#!/bin/bash
# The build pod's driver (oma-image-builder, ADR-0024 "Building").
set -uo pipefail
report() {
  printf '%s' "$1" > /dev/termination-log 2>/dev/null || true
  printf '\\nOMA_BUILD_RESULT %s %s\\n' "$OMA_BUILD_NONCE" "$1"
}
step() { printf '\\n==> %s  [%s]\\n' "$1" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"; }

# The ConfigMap volume holds symlinks; build from plain copies.
ctx=$(mktemp -d)
cp -L ${BUILD_CONTEXT_DIR}/Dockerfile ${BUILD_CONTEXT_DIR}/init.sh ${BUILD_CONTEXT_DIR}/build.env ${BUILD_CONTEXT_DIR}/init-trap.sh "$ctx"/ || { report '{"stage":"build"}'; exit 13; }

step "Pulling the Base Image $OMA_BASE_IMAGE"
started=$SECONDS
if ! buildah pull --quiet "docker://$OMA_BASE_IMAGE" > /dev/null; then report '{"stage":"pull"}'; exit 10; fi
echo "Pulled in $((SECONDS - started)) s"

step "Building: init script, manifest, ownership of /home/user"
started=$SECONDS
buildah build --isolation chroot --pull=never --layers=false --format oci \\
  -f "$ctx/Dockerfile" -t "$OMA_TARGET_IMAGE" "$ctx" 2>&1 | tee /tmp/oma-build.log
status=\${PIPESTATUS[0]}
if [ "$status" -ne 0 ]; then
  if grep -q "^OMA_INIT_FAILED $OMA_BUILD_NONCE " /tmp/oma-build.log; then report '{"stage":"script"}'; exit 11; fi
  if grep -q "^OMA_MANIFEST_FAILED $OMA_BUILD_NONCE" /tmp/oma-build.log; then report '{"stage":"manifest"}'; exit 12; fi
  report '{"stage":"build"}'; exit 13
fi
echo "Built in $((SECONDS - started)) s"

step "Pushing $OMA_TARGET_IMAGE"
started=$SECONDS
if ! buildah push --quiet --digestfile /tmp/oma-digest "$OMA_TARGET_IMAGE" "docker://$OMA_TARGET_IMAGE"; then report '{"stage":"push"}'; exit 14; fi
digest=$(cat /tmp/oma-digest)
echo "Pushed $digest in $((SECONDS - started)) s"
report "{\\"stage\\":\\"pushed\\",\\"digest\\":\\"$digest\\"}"
`;

/** Every file of one build's context, by name in the ConfigMap. */
export function buildContext(input: BuildContextInput): BuildContextFiles {
  return {
    Dockerfile: dockerfile(input),
    "init.sh": input.initScript,
    "build.env": buildEnvFile(input),
    "init-trap.sh": INIT_TRAP,
    "storage.conf": STORAGE_CONF,
    "build.sh": BUILD_DRIVER,
  };
}

/** The driver's report: `stage` is where it ended; `pushed` carries the digest. */
export interface DriverReport {
  stage: "pull" | "script" | "manifest" | "build" | "push" | "pushed";
  digest?: string;
}

const STAGES = new Set(["pull", "script", "manifest", "build", "push", "pushed"]);

/** The driver's report from a termination message, or from the log's last marker of this attempt. */
export function parseDriverReport(text: string | undefined, nonce: string): DriverReport | undefined {
  if (!text) return undefined;
  const candidates = text.trimStart().startsWith("{") ? [text.trim()] : [];
  const marker = `OMA_BUILD_RESULT ${nonce} `;
  for (const line of text.split("\n").reverse()) {
    if (line.startsWith(marker)) { candidates.push(line.slice(marker.length).trim()); break; }
  }
  for (const candidate of candidates) {
    try {
      const report = JSON.parse(candidate) as DriverReport;
      if (!STAGES.has(report.stage)) continue;
      if (report.stage === "pushed" && !/^sha256:[0-9a-f]{64}$/.test(report.digest ?? "")) continue;
      return report;
    } catch { /* not a report */ }
  }
  return undefined;
}

/** What to record for a failed init script, from its attempt's output: the ERR trap's line when it has one. */
export function scriptFailureMessage(logTail: string, nonce: string): string {
  const lines = logTail.split("\n");
  // The earliest is the innermost: a failing subshell is reported again by its parent.
  const located = lines.find((line) => line.startsWith("[oma] init script failed at line "));
  if (located) return `The init script failed at line ${located.slice("[oma] init script failed at line ".length)}`;
  const exit = lines.find((line) => line.startsWith(`OMA_INIT_FAILED ${nonce} exit=`));
  if (exit) return `The init script exited with status ${exit.slice(`OMA_INIT_FAILED ${nonce} exit=`.length)}`;
  return "The init script failed";
}
